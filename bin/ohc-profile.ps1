#Requires -Version 5.1
<#
.SYNOPSIS
    给 PowerShell / cmd 装一个 hdc 包装层，让 hdc shell 自动带上宿主机窗口尺寸

.DESCRIPTION
    问题的根结：hdc 给设备 pty 的尺寸是写死的 80x24，而且它
    不读宿主机控制台、也不转发窗口变化。所以容器里的 TUI
    永远按 80x24 排版，窗口拖多大都没用。

    尺寸只能由宿主机侧读出来再送进去。为了让你不用改习惯
    （还是敲 hdc shell），这个脚本装一层同名包装：

      PowerShell：往 profile 里写一个 function hdc，
                  拦到「hdc shell」且没有额外参数时，
                  改调 bin/ohc-term.ps1（读窗口尺寸 -> 写设备 -> 起会话）
      cmd：      生成 %LOCALAPPDATA%\oh-container\hdc.cmd，
                  把它加到 PATH 前面即可同名覆盖

    其它子命令（file send / install / list targets ...）原样透传给真正的 hdc.exe。

.PARAMETER Uninstall
    移除 PowerShell profile 里的包装块（不动 hdc.cmd）。

.EXAMPLE
    .\bin\ohc-profile.ps1

.EXAMPLE
    .\bin\ohc-profile.ps1 -Uninstall
#>
[CmdletBinding()]
param(
    [switch]$Uninstall
)

$ErrorActionPreference = 'Stop'
try { [Console]::OutputEncoding = [System.Text.Encoding]::UTF8 } catch { }

function Say($m, $c = 'Gray') { Write-Host $m -ForegroundColor $c }

$repo = Split-Path -Parent $PSScriptRoot
$term = Join-Path $repo 'bin\ohc-term.ps1'
if (-not (Test-Path $term)) { Say "找不到 $term" 'Red'; exit 1 }

# ---------------------------------------------------------------- 1. 找真 hdc
$hdcExe = ''
foreach ($c in @(
    "C:\Tools\HarmonyOS\toolchains\hdc.exe",
    "$env:LOCALAPPDATA\Huawei\Sdk\openharmony\toolchains\hdc.exe",
    "$env:ProgramFiles\Huawei\DevEco Studio\sdk\default\openharmony\toolchains\hdc.exe"
)) { if (Test-Path $c) { $hdcExe = $c; break } }
if (-not $hdcExe) {
    $cmd = Get-Command hdc.exe -ErrorAction SilentlyContinue
    if ($cmd) { $hdcExe = $cmd.Source }
}
if (-not $hdcExe) {
    Say "找不到 hdc.exe，包装函数里的真实路径需要你手改。" 'Yellow'
    $hdcExe = 'hdc.exe'
}

# ---------------------------------------------------------------- 2. 生成代码块
# 逐行拼接，不用 here-string：here-string 里的空行在写盘时容易被吃掉，
# 一旦少一个换行就会变成 "$var = 'x'function hdc {" 这种废代码。
$NL = "`r`n"
$lines = @(
    '# >>> ohc-shim >>>'
    '# 由 oh-container/bin/ohc-profile.ps1 生成，请勿手改；重跑脚本即可更新'
    ("`$global:OHC_HOME = '" + $repo + "'")
    ("`$global:OHC_HDC  = '" + $hdcExe + "'")
    ("`$global:OHC_TERM = '" + $term + "'")
    ''
    'function global:hdc {'
    '    $a = @($args)'
    '    # 「hdc shell」且不带命令 -> 走尺寸同步启动器'
    '    if ($a.Count -eq 1 -and "$($a[0])" -eq ''shell'') {'
    '        if (Test-Path $global:OHC_TERM) {'
    '            & $global:OHC_TERM -Quiet'
    '            return'
    '        }'
    '        Write-Host "[ohc] 找不到 $($global:OHC_TERM)，回退到原始 hdc" -ForegroundColor Yellow'
    '    }'
    '    & $global:OHC_HDC @a'
    '}'
    '# <<< ohc-shim <<<'
)
$block = ($lines -join $NL)

# ---------------------------------------------------------------- 3. 装 profile
$docs = [Environment]::GetFolderPath('MyDocuments')
$profiles = @(
    (Join-Path $docs 'WindowsPowerShell\profile.ps1'),
    (Join-Path $docs 'PowerShell\profile.ps1')
)

Say ""
Say "== 安装 hdc 包装层" 'Cyan'
Say "   仓库   : $repo"
Say "   真 hdc : $hdcExe"
Say "   启动器 : $term"
Say ""

foreach ($p in $profiles) {
    $dir = Split-Path -Parent $p
    if (-not (Test-Path $dir)) {
        if ($Uninstall) { continue }
        try { New-Item -ItemType Directory -Force -Path $dir | Out-Null } catch { continue }
    }

    $old = ''
    if (Test-Path $p) {
        try { $old = [System.IO.File]::ReadAllText($p) } catch { $old = '' }
    }

    # 先剥掉旧的包装块
    $stripped = [regex]::Replace($old, '(?s)\r?\n?# >>> ohc-shim >>>.*?# <<< ohc-shim <<<\r?\n?', $NL)

    if ($Uninstall) {
        if ($stripped -ne $old) {
            [System.IO.File]::WriteAllText($p, $stripped, (New-Object System.Text.UTF8Encoding($true)))
            Say "  已移除 : $p" 'Green'
        } else {
            Say "  无包装块: $p"
        }
        continue
    }

    $new = $stripped.TrimEnd() + $NL + $block + $NL
    [System.IO.File]::WriteAllText($p, $new, (New-Object System.Text.UTF8Encoding($true)))
    Say "  已写入 : $p" 'Green'
}

if ($Uninstall) { Say ""; Say "卸载完成。重开一个 PowerShell 窗口生效。" 'Cyan'; exit 0 }

# ---------------------------------------------------------------- 4. 生成 hdc.cmd（给 cmd 用）
# 注意：cmd 按 ANSI 代码页读批处理，写 UTF-8 中文会变乱码，
# 所以注释一律用英文，编码用纯 ASCII。
$shimDir = Join-Path $env:LOCALAPPDATA 'oh-container'
$batPath = ''
try {
    if (-not (Test-Path $shimDir)) { New-Item -ItemType Directory -Force -Path $shimDir | Out-Null }
    $bat = @(
        '@echo off'
        'rem Generated by oh-container/bin/ohc-profile.ps1 - do not edit'
        'rem Purpose: make plain "hdc shell" carry the host console size'
        'rem Usage  : put this folder FIRST in PATH'
        'setlocal'
        'rem %~1 / %~2 strip the outer quotes, so comparing them is safe'
        'rem for normal use. Comparing %* would break on any quoted argument.'
        'if /i "%~1"=="shell" if "%~2"=="" goto :ohc_interactive'
        'goto :ohc_passthru'
        ':ohc_interactive'
        ('    powershell -NoProfile -ExecutionPolicy Bypass -File "' + $term + '" -Quiet')
        '    exit /b'
        ':ohc_passthru'
        ('"' + $hdcExe + '" %*')
    ) -join "`r`n"
    $batPath = Join-Path $shimDir 'hdc.cmd'
    [System.IO.File]::WriteAllText($batPath, $bat + "`r`n", [System.Text.Encoding]::ASCII)
    Say "  已生成 : $batPath" 'Green'
} catch {
    Say "  生成 hdc.cmd 失败: $($_.Exception.Message)" 'Yellow'
    $batPath = ''
}

# ---------------------------------------------------------------- 5. 收尾提示
Say ""
Say "== 接下来" 'Cyan'
Say "  1) 重开一个 PowerShell 窗口（profile 只在启动时加载）"
Say "  2) 直接敲  hdc shell    —— 尺寸会自动跟着窗口走"
Say ""
if ($batPath) {
    Say "  cmd 用户：把下面这个目录加到 PATH 最前面" 'Gray'
    Say "     $shimDir" 'Gray'
    Say "  然后 cmd 里敲 hdc shell 也一样生效" 'Gray'
    Say ""
}
Say "  验证包装是否生效：Get-Command hdc 应显示 Function" 'Gray'
Say "  临时用原始 hdc：  hdc.exe shell" 'Gray'
Say ""
Say "  若提示无法加载配置文件，先执行：" 'Yellow'
Say "     Set-ExecutionPolicy -Scope CurrentUser RemoteSigned" 'Yellow'
Say ""
